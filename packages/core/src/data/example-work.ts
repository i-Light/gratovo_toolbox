const DAY = 86_400_000;

/** A local time on the day of `now` plus `offset` days. */
function dayTime(now: number, offset: number, hours: number, minutes: number): number {
  const date = new Date(now);
  date.setDate(date.getDate() + offset);
  date.setHours(hours, minutes, 0, 0);
  return date.getTime();
}

