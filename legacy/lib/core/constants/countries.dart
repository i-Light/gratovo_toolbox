/// Code -> full name, built once on first use.
///
/// A map rather than a linear scan over [kAllCountries]: the influencer list
/// resolves a country name for every visible row, and a 249-entry scan per row
/// per rebuild is real work for a lookup that is the same every time.
final Map<String, String> _countryNamesByCode = {
  for (final country in kAllCountries) country.code: country.name,
};

/// The full country name for an ISO-3166 alpha-2 code.
///
/// Falls back to the code itself, which is the honest answer for a code
/// YouTube reports that is not in this list (it happens — retired codes, and
/// the occasional non-standard value) and keeps it filterable rather than
/// blank.
String countryNameFor(String code) =>
    _countryNamesByCode[code.toUpperCase()] ?? code;
