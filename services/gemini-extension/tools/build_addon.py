#!/usr/bin/env python3
"""Build the Firefox variant of the Gemini Bridge extension (unpacked folder and .xpi).

One source tree serves every browser:

* Chrome / Edge load ``services/gemini-extension/`` unpacked, as always (MV3, service worker).
* Firefox gets a *generated* build from this module: an unpacked folder (the app loads it as a
  temporary add-on) and a deterministic ``.xpi`` (what Mozilla signs for a permanent install).

Only the standard library is used, on purpose: the same file runs at build time and inside the
app's bundled interpreter, where there is no Node and no pip.

Public API (fixed by the Gemini contract, CONTRACT_GEMINI.md section 1)::

    build_firefox(src_dir, out_dir) -> {"dir", "id", "version", "manifestVersion"}
    build_xpi(src_dir, out_file)    -> {"path", "id", "version", "sha256"}

Both accept the keyword-only extras ``mode``, ``update_url`` and ``token``. With a ``token``
(64 lowercase hex characters, the bridge's per-launch token) the build gains a generated
``bridge-token.js`` (``self.GB_BRIDGE_TOKEN = "<token>";``) listed FIRST among the background
scripts, so ``background.js`` can put it in its hello. The source folder never holds that file; ``describe(src_dir)`` reads the
shipped version without building anything.

Command line::

    python tools/build_addon.py info
    python tools/build_addon.py firefox --out build/firefox [--token <64 hex>]
    python tools/build_addon.py xpi --out build/gemini-bridge.xpi
"""

from __future__ import annotations

import argparse
import copy
import hashlib
import io
import json
import os
import re
import shutil
import sys
import zipfile
from pathlib import Path
from typing import Iterable, Optional

#: The add-on id every consumer relies on (CONTRACT_GEMINI.md section 1).
ADDON_ID = "gemini-bridge@gratovo.app"

#: Oldest Firefox the build declares support for. The manifest key `data_collection_permissions`
#: (required by AMO for new add-ons) exists since 140 on desktop, but the linter only accepts a
#: declared minimum of 142, the first release that supports it on every platform the manifest could
#: be read for; every API the extension uses (scripting in MV2, storage.session,
#: tabs.autoDiscardable) is older than either.
GECKO_MIN_VERSION = "142.0"

#: Which manifest the Firefox build uses. "mv2" = persistent background page, "mv3" = event page.
#: The reasoning and the measurements are in README.md ("Firefox: MV2 or MV3").
FIREFOX_MODE = "mv2"

#: The scripts of the Firefox background page, in load order. A service worker cannot be used there
#: (Firefox has none), so what `importScripts()` pulls in for Chrome is listed here instead;
#: `test_build_addon.py` checks this list against the `importScripts(...)` call in background.js.
BACKGROUND_SCRIPTS = ("compat.js", "content/locators.js", "background.js")

#: Never shipped: dev tooling, tests, docs and build output.
EXCLUDED_DIRS = frozenset({
    "test", "tests", "tools", "node_modules", "dist", "build", "out", ".git", ".github", ".vscode",
    ".idea", "__pycache__",
})
#: Generated by the build when a token is given; never taken from the source folder.
TOKEN_FILE = "bridge-token.js"
_TOKEN_RE = re.compile(r"^[0-9a-f]{64}$")

EXCLUDED_NAMES = frozenset({
    TOKEN_FILE, "README.md", "package.json", "package-lock.json", ".gitignore", ".gitattributes", "Thumbs.db",
    ".DS_Store", "desktop.ini",
})
EXCLUDED_SUFFIXES = (".md", ".map", ".pyc", ".pyo", ".log", ".tmp", ".orig", ".rej", ".swp", ".bak", ".xpi", ".zip")

#: Text files are normalised to LF so the archive does not depend on the checkout's line endings.
_TEXT_SUFFIXES = (".js", ".json", ".html", ".css", ".svg", ".txt")

_VERSION_RE = re.compile(r"^\d{1,9}(\.\d{1,9}){0,3}$")


class BuildError(Exception):
    """The source tree cannot be turned into a valid add-on; the message says what to fix."""


# --------------------------------------------------------------------------------------
# Reading the source
# --------------------------------------------------------------------------------------
def read_manifest(src_dir: Path) -> dict:
    if not Path(src_dir).is_dir():
        raise BuildError("source directory %s does not exist" % src_dir)
    path = Path(src_dir) / "manifest.json"
    if not path.is_file():
        raise BuildError("no manifest.json in %s (is this the services/gemini-extension folder?)" % src_dir)
    try:
        manifest = json.loads(path.read_text(encoding="utf-8-sig"))
    except ValueError as e:
        raise BuildError("manifest.json is not valid JSON: %s" % e) from e
    if not isinstance(manifest, dict):
        raise BuildError("manifest.json must contain a JSON object")
    if manifest.get("manifest_version") != 3:
        raise BuildError("the source manifest must be Manifest V3 (the Firefox build derives from it)")
    version = manifest.get("version")
    if not isinstance(version, str) or not _VERSION_RE.match(version):
        raise BuildError("manifest version %r is not a Firefox-valid version (1-4 dot-separated integers)" % (version,))
    if not manifest.get("name"):
        raise BuildError("manifest.json has no name")
    return manifest


def describe(src_dir: Path) -> dict:
    """What the source tree would ship, without building anything."""
    manifest = read_manifest(Path(src_dir))
    return {"id": ADDON_ID, "version": manifest["version"], "name": manifest.get("name"), "sourceManifestVersion": 3, "firefoxMode": FIREFOX_MODE}


def _is_excluded(rel: Path, is_dir: bool) -> bool:
    name = rel.name
    if is_dir:
        return name in EXCLUDED_DIRS or name.startswith(".")
    return name in EXCLUDED_NAMES or name.startswith(".") or name.lower().endswith(EXCLUDED_SUFFIXES)


def collect_files(src_dir: Path) -> list:
    """Relative POSIX paths of every file that ships, sorted (the sort makes the archive deterministic)."""
    src_dir = Path(src_dir)
    found = []
    for dirpath, dirnames, filenames in os.walk(src_dir):
        here = Path(dirpath)
        dirnames[:] = sorted(d for d in dirnames if not _is_excluded((here / d).relative_to(src_dir), True) and not (here / d).is_symlink())
        for fn in sorted(filenames):
            p = here / fn
            rel = p.relative_to(src_dir)
            if p.is_symlink() or _is_excluded(rel, False):
                continue
            found.append(rel.as_posix())
    return sorted(found)


# --------------------------------------------------------------------------------------
# The manifest transform
# --------------------------------------------------------------------------------------
def firefox_manifest(src: dict, mode: Optional[str] = None, update_url: Optional[str] = None, token: Optional[str] = None) -> dict:
    """The Firefox manifest derived from the (MV3, Chrome/Edge) source manifest. Pure function."""
    mode = mode or FIREFOX_MODE
    if mode not in ("mv2", "mv3"):
        raise BuildError("mode must be 'mv2' or 'mv3', not %r" % (mode,))
    scripts = list(BACKGROUND_SCRIPTS)
    if token is not None:
        scripts.insert(0, TOKEN_FILE)
    permissions = list(src.get("permissions") or [])
    host_permissions = list(src.get("host_permissions") or [])

    gecko = {"id": ADDON_ID, "strict_min_version": GECKO_MIN_VERSION, "data_collection_permissions": {"required": ["none"]}}
    if update_url:
        gecko["update_url"] = update_url

    out = {}
    for key, value in src.items():
        if key == "manifest_version":
            out[key] = 2 if mode == "mv2" else 3
        elif key == "permissions":
            merged = list(permissions)
            if mode == "mv2":
                merged += [h for h in host_permissions if h not in merged]
            out[key] = merged
        elif key == "host_permissions":
            if mode == "mv3":
                out[key] = host_permissions
        elif key == "background":
            out[key] = {"scripts": scripts, "persistent": True} if mode == "mv2" else {"scripts": scripts}
        elif key == "action":
            out["browser_action" if mode == "mv2" else "action"] = copy.deepcopy(value)
        elif key in ("browser_specific_settings", "applications"):
            continue  # the source has none; if one appears, ours wins
        else:
            out[key] = copy.deepcopy(value)
    if mode == "mv2" and "permissions" not in out:
        out["permissions"] = host_permissions
    out["browser_specific_settings"] = {"gecko": gecko}
    return out


def _manifest_bytes(manifest: dict) -> bytes:
    return (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def _referenced_files(manifest: dict) -> set:
    """Every file the manifest points at."""
    refs = set()
    bg = manifest.get("background") or {}
    refs.update(bg.get("scripts") or [])
    if bg.get("service_worker"):
        refs.add(bg["service_worker"])
    for cs in manifest.get("content_scripts") or []:
        refs.update(cs.get("js") or [])
        refs.update(cs.get("css") or [])
    for key in ("action", "browser_action", "page_action"):
        act = manifest.get(key) or {}
        if act.get("default_popup"):
            refs.add(act["default_popup"])
        icon = act.get("default_icon")
        if isinstance(icon, str):
            refs.add(icon)
        elif isinstance(icon, dict):
            refs.update(icon.values())
    icons = manifest.get("icons")
    if isinstance(icons, dict):
        refs.update(icons.values())
    return refs


def _check_references(manifest: dict, files: Iterable[str], read) -> None:
    shipped = set(files)
    missing = sorted(r for r in _referenced_files(manifest) if r not in shipped)
    if missing:
        raise BuildError("the manifest references files that are not shipped: " + ", ".join(missing))
    # A popup page that loads a script or stylesheet which is missing is broken in a way nobody sees until they click.
    for act_key in ("action", "browser_action"):
        popup = (manifest.get(act_key) or {}).get("default_popup")
        if not popup:
            continue
        html = read(popup).decode("utf-8", "replace")
        base = Path(popup).parent
        for ref in re.findall(r'''(?:src|href)\s*=\s*["']([^"'#?]+)''', html):
            if re.match(r"^[a-z][a-z0-9+.-]*:", ref) or ref.startswith("//"):
                continue  # external: not ours to ship
            target = (base / ref).as_posix() if not ref.startswith("/") else ref.lstrip("/")
            target = os.path.normpath(target).replace("\\", "/")
            if target not in shipped:
                raise BuildError("%s refers to %s, which is not shipped" % (popup, ref))


# --------------------------------------------------------------------------------------
# Rendering: the file set of a build
# --------------------------------------------------------------------------------------
def _check_token(token: Optional[str]) -> Optional[str]:
    if token is None:
        return None
    if not isinstance(token, str) or not _TOKEN_RE.fullmatch(token):
        raise ValueError("token must be 64 lowercase hex characters")
    return token


def _render(src_dir: Path, mode: Optional[str], update_url: Optional[str], token: Optional[str] = None):
    src_dir = Path(src_dir)
    token = _check_token(token)
    source_manifest = read_manifest(src_dir)
    manifest = firefox_manifest(source_manifest, mode, update_url, token)
    names = collect_files(src_dir)
    if token is not None:
        names = sorted(names + [TOKEN_FILE])
    _check_references(manifest, names, lambda rel: (src_dir / rel).read_bytes())
    files = []
    for rel in names:
        if rel == "manifest.json":
            data = _manifest_bytes(manifest)
        elif rel == TOKEN_FILE:
            data = ('self.GB_BRIDGE_TOKEN = "%s";\n' % token).encode("utf-8")
        else:
            data = (src_dir / rel).read_bytes()
            if rel.lower().endswith(_TEXT_SUFFIXES):
                data = data.replace(b"\r\n", b"\n")
        files.append((rel, data))
    return manifest, files


# --------------------------------------------------------------------------------------
# Output
# --------------------------------------------------------------------------------------
def _sync_tree(files: list, out_dir: Path) -> None:
    """Make `out_dir` hold exactly `files`. Unchanged files are left alone (so a browser that has the
    folder loaded does not see spurious modifications); files that no longer belong are removed."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    wanted = {rel for rel, _ in files}
    for rel, data in files:
        target = out_dir / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        try:
            if target.is_file() and target.read_bytes() == data:
                continue
        except OSError:
            pass
        target.write_bytes(data)
    # stale files, then empty directories (deepest first)
    for dirpath, dirnames, filenames in os.walk(out_dir, topdown=False):
        here = Path(dirpath)
        for fn in filenames:
            rel = (here / fn).relative_to(out_dir).as_posix()
            if rel not in wanted:
                try:
                    (here / fn).unlink()
                except OSError:
                    pass
        if here != out_dir:
            try:
                here.rmdir()  # only succeeds when empty
            except OSError:
                pass


def _zip_bytes(files: list) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for rel, data in files:
            info = zipfile.ZipInfo(rel, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.create_system = 3  # unix: same header bytes whichever OS builds it
            info.external_attr = 0o100644 << 16
            zf.writestr(info, data, compresslevel=9)
    return buf.getvalue()


def build_firefox(src_dir: Path, out_dir: Path, *, mode: Optional[str] = None, update_url: Optional[str] = None, token: Optional[str] = None) -> dict:
    """Write the unpacked, Firefox-ready add-on into `out_dir` (created / updated in place)."""
    manifest, files = _render(Path(src_dir), mode, update_url, token)
    _sync_tree(files, Path(out_dir))
    return {"dir": str(Path(out_dir)), "id": ADDON_ID, "version": manifest["version"], "manifestVersion": manifest["manifest_version"]}


def build_xpi(src_dir: Path, out_file: Path, *, mode: Optional[str] = None, update_url: Optional[str] = None, token: Optional[str] = None) -> dict:
    """Write the add-on as a deterministic .xpi: sorted entries, fixed timestamps, LF text, no dev files."""
    manifest, files = _render(Path(src_dir), mode, update_url, token)
    data = _zip_bytes(files)
    out_file = Path(out_file)
    out_file.parent.mkdir(parents=True, exist_ok=True)
    tmp = out_file.with_name(out_file.name + ".tmp")
    tmp.write_bytes(data)
    os.replace(tmp, out_file)
    return {"path": str(out_file), "id": ADDON_ID, "version": manifest["version"], "sha256": hashlib.sha256(data).hexdigest()}


# --------------------------------------------------------------------------------------
# Command line
# --------------------------------------------------------------------------------------
def _default_src() -> Path:
    return Path(__file__).resolve().parent.parent


def main(argv: Optional[list] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name, help_ in (("info", "print id and version of the shipped source"), ("firefox", "build the unpacked Firefox add-on"), ("xpi", "build the .xpi")):
        p = sub.add_parser(name, help=help_)
        p.add_argument("--src", type=Path, default=_default_src(), help="extension source (default: this repo's services/gemini-extension)")
        if name != "info":
            p.add_argument("--out", type=Path, required=True)
            p.add_argument("--mode", choices=("mv2", "mv3"), default=None)
            p.add_argument("--update-url", default=None, help="value for browser_specific_settings.gecko.update_url")
            p.add_argument("--token", default=None, help="per-launch bridge token (64 lowercase hex); writes bridge-token.js")
    args = ap.parse_args(argv)
    try:
        if args.cmd == "info":
            result = describe(args.src)
        elif args.cmd == "firefox":
            result = build_firefox(args.src, args.out, mode=args.mode, update_url=args.update_url, token=args.token)
        else:
            result = build_xpi(args.src, args.out, mode=args.mode, update_url=args.update_url, token=args.token)
    except (BuildError, ValueError) as e:
        print("build_addon: " + str(e), file=sys.stderr)
        return 2
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
